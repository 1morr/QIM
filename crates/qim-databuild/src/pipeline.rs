/// 建出的一份資料包，與寫出時旁邊放的授權與 manifest。
struct LicensedPack {
    pack: BuiltPack,
    /// manifest 的 `version`（semver）。資料包的內容改了就要加（plan §4.6）。
    version: &'static str,
    /// 寫進 `LICENSE`、`NOTICE` 的來源。
    sources: Vec<packing::PackSource>,
    /// NOTICE 最後說明怎麼用來源的一段。
    about: String,
}

impl LicensedPack {
    fn new<P: Pack>(
        name: &'static str,
        pack: &P,
        version: &'static str,
        sources: Vec<packing::PackSource>,
        about: impl Into<String>,
    ) -> Result<Self, Error> {
        Ok(Self {
            pack: BuiltPack::new(name, pack)
                .map_err(|e| Error::invalid(format!("{name}資料包"), e.to_string()))?,
            version,
            sources,
            about: about.into(),
        })
    }
}

/// 一次建出的所有資料包與建置統計；`--verify` 會再建一次比。
struct PackSet {
    packs: Vec<LicensedPack>,
    lexicon: LexiconSummary,
    /// 粵典詞庫的統計；粵典的來源出問題而略過時是 `None`，原因在 `skipped`。
    words_hk: Option<WordsHkSummary>,
    skipped: Vec<Skipped>,
    language_model: bigram::Summary,
    /// 兩份詞級 trigram 的統計，方案指名的那份在前。
    word_trigrams: Vec<word_trigram::Summary>,
    english: english::Counts,
    emoji: emoji::Counts,
}

impl PackSet {
    fn built(&self) -> Vec<BuiltPack> {
        self.packs.iter().map(|p| p.pack.clone()).collect()
    }
}

