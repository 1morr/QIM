/// 建一次速成資料包的結果；`--verify` 會再建一次比。
struct QuickBuild {
    rows: Vec<libcangjie::Row>,
    /// `Unihan_DictionaryLikeData.txt` 的內容。
    dictionary_like: String,
    pack: SchemePack,
    /// 方案指名的字根提示資料包，由同樣的列建（[`radical_hint::hints`]）。
    radical_hint: RadicalHintPack,
}

/// 建出的一份資料包，與寫出時旁邊放的授權。
struct LicensedPack {
    pack: BuiltPack,
    /// 寫進 `LICENSE`、`NOTICE` 的來源。
    sources: Vec<packing::PackSource>,
    /// NOTICE 最後說明怎麼用來源的一段。
    about: String,
}

impl LicensedPack {
    fn new<P: Pack>(
        name: &'static str,
        pack: &P,
        sources: Vec<packing::PackSource>,
        about: impl Into<String>,
    ) -> Result<Self, Error> {
        Ok(Self {
            pack: BuiltPack::new(name, pack)
                .map_err(|e| Error::invalid(format!("{name}資料包"), e.to_string()))?,
            sources,
            about: about.into(),
        })
    }
}

/// 一次建出的所有資料包與建置統計；`--verify` 會再建一次比。
struct PackSet {
    packs: Vec<LicensedPack>,
    lexicon: LexiconSummary,
    language_model: bigram::Summary,
    english: english::Counts,
    emoji: emoji::Counts,
}

impl PackSet {
    fn built(&self) -> Vec<BuiltPack> {
        self.packs.iter().map(|p| p.pack.clone()).collect()
    }
}

/// 寫出的一份資料包。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WrittenPack {
    /// 給人看的種類名（`速成`、`詞庫`…）。
    pub name: &'static str,
    pub id: String,
    /// `build/packs/<id>/<id>.pack`。
    pub path: PathBuf,
    pub sha256: String,
}

#[derive(Debug)]
pub struct Outcome {
    /// 寫出的資料包，依建置順序。
    pub packs: Vec<WrittenPack>,
    pub lexicon: LexiconSummary,
    pub language_model: bigram::Summary,
    pub english: english::Counts,
    pub emoji: emoji::Counts,
    /// 預設 Gboard 速成佈局（[`gboard::layout`]）。
    pub layout_path: PathBuf,
    /// 各語料的句數。
    pub corpora: Vec<CorpusSummary>,
    /// 個人集轉出的統計；沒有 [`personal::USERDB`] 時是 `None`。
    pub personal: Option<personal::Counts>,
    /// 只有要求驗證時才有。
    pub report: Option<Report>,
}

/// 在 repo 根目錄 `root` 建速成資料包與各語料，再用語料建其餘資料包（清單在 `build_packs`）：
/// 每個資料包寫到 `build/packs/<id>/`，旁邊放 `LICENSE` 與 `NOTICE`。
/// 另把預設 Gboard 速成佈局（數字列關與開兩份）寫到 `build/layouts/`。
/// 來源下載到 `cache` 下的 `sources/`（[`sources::default_cache_dir`]）。
pub fn run(root: &Path, cache: &Path, fetch: &dyn Fetch, verify: bool) -> Result<Outcome, Error> {
    let read = |rel: &str| {
        let path = root.join(rel);
        std::fs::read_to_string(&path).map_err(Error::io(path))
    };
    let all = sources::parse(&read(SOURCES)?)?;
    let source_of = |id: &str| {
        all.source
            .get(id)
            .ok_or_else(|| Error::invalid(SOURCES, format!("沒有 [source.{id}]")))
    };
    let cache = cache.join("sources");
    let load = |id: &str, path: &str| -> Result<Vec<u8>, Error> {
        sources::load(&cache, id, source_of(id)?.file(path)?, fetch)
    };
    let load_text = |id: &str, path: &str| -> Result<String, Error> {
        String::from_utf8(load(id, path)?).map_err(|e| Error::invalid(path, e.to_string()))
    };

    // 每次都從快取與方案檔重讀，`--verify` 的第二次建置才是真的重建。
    let build_quick = || -> Result<QuickBuild, Error> {
        let rows = libcangjie::parse(&load_text(LIBCANGJIE, TABLE)?)?;
        let dictionary_like = unihan::read_archive(&load(UNIHAN, UNIHAN_ZIP)?)?;
        let grades = unihan::grade_levels(&dictionary_like)?;
        let dictionary = |file: &str| opencc::parse(file, &load_text(OPENCC, file)?);
        let simplified = simplified::characters(
            &rows,
            &simplified::References {
                st: &dictionary(opencc::ST_CHARACTERS)?,
                ts: &dictionary(opencc::TS_CHARACTERS)?,
                hk_variants: &dictionary(opencc::HK_VARIANTS)?,
                hk_glyphs: &unihan::hk_glyphs(&dictionary_like)?,
            },
        );
        let pack = build_scheme_pack(
            &rows,
            &grades,
            &simplified,
            scheme::parse(&read(QUICK_SCHEME)?)?,
        );
        let radical_hint = RadicalHintPack {
            id: named(&pack.scheme.packs.radical_hint, "radical_hint", "字根提示")?,
            hints: radical_hint::hints(&rows),
        };
        Ok(QuickBuild {
            rows,
            dictionary_like,
            pack,
            radical_hint,
        })
    };
    let quick = build_quick()?;
    let write =
        |path: PathBuf, contents: &[u8]| std::fs::write(&path, contents).map_err(Error::io(path));

    let transcoder = Transcoder::new(&quick.rows);
    // 語料轉成香港繁體後換回常見寫法（brief §4.1、plan §4.3）。
    let forms = CommonForms::from_opencc(&quick.pack.code_table)?;
    let mut corpora = Vec::new();
    let mut corpus_checks = Vec::new();
    let mut attributions: Vec<(Group, String)> = Vec::new();
    // 各語料兩次建置的字頻與權重，給詞庫資料包。
    let mut chars: Vec<(String, u64)> = Vec::new();
    let mut second_chars: Vec<(String, u64)> = Vec::new();
    // 已分詞語料 train 切分的詞與次數（兩次建置各一份），給詞庫補詞；與對不上而略過的話輪數。
    let mut words = WordCounts::default();
    let mut second_words = WordCounts::default();
    // 驗證用：各語料的基準檔內容與 train 檔，洩漏要拿每個基準集比對所有 train。
    let mut benches: Vec<(String, String)> = Vec::new();
    // 各語料的 train 切分與權重，bigram 用；洩漏檢查也比對它們。
    let mut trains: Vec<(PathBuf, u64)> = Vec::new();
    for corpus in &CORPORA {
        let source = source_of(corpus.source_id)?;
        let paths = source
            .files
            .iter()
            .map(|file| sources::cached(&cache, corpus.source_id, file, fetch))
            .collect::<Result<Vec<_>, _>>()?;
        let dir = corpora::build_dir(root, corpus.name);
        std::fs::create_dir_all(&dir).map_err(Error::io(&dir))?;
        let (train_path, dev_path) = (dir.join("train.txt"), dir.join("dev.txt"));
        let create = |path: &Path| {
            File::create(path)
                .map(|f| Hashed::new(BufWriter::new(f)))
                .map_err(Error::io(path))
        };
        let first = build_corpus(
            corpus,
            &paths,
            &forms,
            &transcoder,
            create(&train_path)?,
            create(&dev_path)?,
            &dir,
        )?;
        let bench_dir = root.join(corpus.group.dir());
        std::fs::create_dir_all(&bench_dir).map_err(Error::io(&bench_dir))?;
        let bench_rel = format!("{}/{}.tsv", corpus.group.dir(), corpus.name);
        write(root.join(&bench_rel), first.bench.as_bytes())?;
        let context_dir = root.join(corpus.group.context_dir());
        std::fs::create_dir_all(&context_dir).map_err(Error::io(&context_dir))?;
        let context_rel = format!("{}/{}.tsv", corpus.group.context_dir(), corpus.name);
        write(root.join(&context_rel), first.context_bench.as_bytes())?;
        write(dir.join("chars.tsv"), first.chars.as_bytes())?;
        write(
            corpora::dev_items_path(root, corpus.name),
            first.dev_items.as_bytes(),
        )?;
        write(
            corpora::dev_context_items_path(root, corpus.name),
            first.dev_context_items.as_bytes(),
        )?;
        corpora.push(CorpusSummary {
            name: corpus.name.into(),
            counts: first.counts,
            bench_sentences: first.bench.lines().count(),
            bench: bench_rel.into(),
            context_sentences: first.context_bench.lines().count(),
            context_bench: context_rel.into(),
        });
        attributions.push((corpus.group, corpus.attribution(source)));
        if verify {
            // 第二次從快取重讀來源，只算 sha256、不寫檔。
            let sink = || Hashed::new(io::sink());
            let second = build_corpus(corpus, &paths, &forms, &transcoder, sink(), sink(), &dir)?;
            corpus_checks.extend(
                verify::corpus(
                    corpus.name,
                    &transcoder,
                    &first.bench,
                    &first.context_bench,
                    open(&train_path)?,
                    open(&dev_path)?,
                    &first.digests(),
                    &second.digests(),
                )
                .map_err(Error::io(&dir))?,
            );
            second_chars.push((second.chars, corpus.weight));
            second_words.merge(corpus.train_words(&paths, &forms, &transcoder)?);
        }
        trains.push((train_path, corpus.weight));
        chars.push((first.chars, corpus.weight));
        words.merge(corpus.train_words(&paths, &forms, &transcoder)?);
        if verify {
            benches.push((corpus.name.to_string(), first.bench));
            benches.push((format!("{} 有前文", corpus.name), first.context_bench));
        }
    }
    for group in Group::ALL {
        let sections: Vec<String> = attributions
            .iter()
            .filter(|(g, _)| *g == group)
            .map(|(_, section)| section.clone())
            .collect();
        write(
            root.join(group.dir()).join("ATTRIBUTION.md"),
            corpora::attribution_file(group, &sections).as_bytes(),
        )?;
    }

    // 詞庫的碼由這次建出的速成碼表展開，字頻由各語料的 train 乘上權重相加；每次從快取重讀 essay.txt。
    // 詞和粵語語料一樣經 `t2hk` 再換回常見寫法（rime-essay 是 OpenCC 標準寫法，brief §4.1）。
    let essay_converter = corpora::Converter::new(corpora::Conversion::T2hk, forms.clone())?;
    let build_lexicon = |quick: &QuickBuild,
                         chars: &[(String, u64)],
                         words: &WordCounts|
     -> Result<(LexiconPack, LexiconSummary), Error> {
        let tables: Vec<(&str, u64)> = chars.iter().map(|(t, w)| (t.as_str(), *w)).collect();
        let frequency = lexicon::char_frequency(&tables)?;
        let characters = frequency.len();
        let (lexicon, counts) = lexicon::build(
            &load_text(RIME_ESSAY, ESSAY)?,
            &read(lexicon::COLLOQUIAL_PATH)?,
            &words.words,
            &quick.pack.code_table,
            &Transcoder::new(&quick.rows),
            frequency,
            &lexicon::Forms {
                normalize: &|word| essay_converter.convert(word),
                both: forms.both(),
            },
        )?;
        let pack = LexiconPack {
            id: named(&quick.pack.scheme.packs.lexicon, "lexicon", "詞庫")?,
            lexicon,
        };
        Ok((
            pack,
            LexiconSummary {
                counts,
                characters,
                corpus_seen: words.words.len(),
                unaligned: words.unaligned,
            },
        ))
    };
    // bigram 由各語料寫出的 train 切分訓練；每次重讀檔案，`--verify` 的第二次才是真的重訓。
    let build_language_model =
        |quick: &QuickBuild| -> Result<(LanguageModelPack, bigram::Summary), Error> {
            let mut counter = bigram::Counter::default();
            for (path, weight) in &trains {
                counter.add(open(path)?, *weight).map_err(Error::io(path))?;
            }
            let vocabulary = quick
                .pack
                .code_table
                .iter()
                .flat_map(|(_, entries)| entries.iter().filter(|e| !e.extension).map(|e| e.text))
                .collect::<BTreeSet<char>>()
                .len();
            let (model, summary) =
                bigram::train(&counter, vocabulary, bigram::MIN_COUNT, forms.both());
            let pack = LanguageModelPack {
                id: named(
                    &quick.pack.scheme.packs.language_model,
                    "language_model",
                    "語言模型",
                )?,
                model,
            };
            Ok((pack, summary))
        };
    // 加一種資料包只在這裡加一項：建法、授權來源與 NOTICE 的說明（plan §4）。
    // 每次從快取重讀來源，`--verify` 的第二次才是真的重建。
    let build_packs = |quick: &QuickBuild,
                       chars: &[(String, u64)],
                       words: &WordCounts|
     -> Result<PackSet, Error> {
        let (lexicon, lexicon_summary) = build_lexicon(quick, chars, words)?;
        let (language_model, language_model_summary) = build_language_model(quick)?;
        let simplifier = SimplifierPack {
            id: SIMPLIFIER_ID.into(),
            simplifier: opencc::hk2s(|file| load_text(OPENCC, file))?,
        };
        // 只留速成打得出的詞（a–y）。
        let (words, english_counts) =
            english::words(&load(SCOWL, SCOWL_ZIP)?, &quick.pack.scheme.alphabet)?;
        let english = EnglishPack {
            id: ENGLISH_ID.into(),
            words,
        };
        // 字詞照詞庫的寫法換；有字沒有速成碼的字詞打不出，不收。
        let annotations = emoji::CLDR_ANNOTATIONS
            .iter()
            .map(|(name, path)| Ok((*name, load_text(emoji::CLDR, path)?)))
            .collect::<Result<Vec<_>, Error>>()?;
        let coded: HashSet<char> = quick
            .pack
            .code_table
            .iter()
            .flat_map(|(_, entries)| entries.iter().map(|e| e.text))
            .collect();
        let built_emoji = emoji::table(
            &annotations
                .iter()
                .map(|(name, xml)| emoji::Annotations { name, xml })
                .collect::<Vec<_>>(),
            &load_text(emoji::EMOJI_TEST, emoji::EMOJI_TEST_FILE)?,
            &|word| essay_converter.convert(word),
            &|c| coded.contains(&c),
            emoji::MAX_KEYWORD_EMOJI,
        )?;
        let emoji = EmojiPack {
            id: EMOJI_ID.into(),
            emoji: built_emoji.table,
        };
        let scheme = &quick.pack.scheme.id;
        let packs = vec![
            LicensedPack::new("速成", &quick.pack, packing::QUICK.into(), QUICK_ABOUT)?,
            LicensedPack::new(
                "詞庫",
                &lexicon,
                packing::lexicon_sources(),
                lexicon_about(&lexicon.id, scheme),
            )?,
            LicensedPack::new(
                "語言模型",
                &language_model,
                packing::language_model_sources(),
                language_model_about(&language_model.id),
            )?,
            LicensedPack::new(
                "字根提示",
                &quick.radical_hint,
                packing::RADICAL_HINT.into(),
                RADICAL_HINT_ABOUT,
            )?,
            LicensedPack::new(
                "簡繁",
                &simplifier,
                packing::SIMPLIFIER.into(),
                SIMPLIFIER_ABOUT,
            )?,
            LicensedPack::new("英文", &english, packing::ENGLISH.into(), ENGLISH_ABOUT)?,
            LicensedPack::new(
                "emoji",
                &emoji,
                packing::EMOJI.into(),
                EMOJI_ABOUT.replace("{max}", &emoji::MAX_KEYWORD_EMOJI.to_string()),
            )?,
        ];
        Ok(PackSet {
            packs,
            lexicon: lexicon_summary,
            language_model: language_model_summary,
            english: english_counts,
            emoji: built_emoji.counts,
        })
    };
    let first = build_packs(&quick, &chars, &words)?;
    let packs = first
        .packs
        .iter()
        .map(|licensed| {
            let packed = packing::resolve(&licensed.sources, &all, load_text, read)?;
            write_pack(root, licensed, &packed)
        })
        .collect::<Result<Vec<_>, Error>>()?;

    let layouts = root.join(LAYOUTS);
    std::fs::create_dir_all(&layouts).map_err(Error::io(&layouts))?;
    let layout_path = layouts.join(gboard::FILE);
    write(layout_path.clone(), gboard::layout().to_json().as_bytes())?;
    write(
        layouts.join(gboard::NUMBER_ROW_FILE),
        gboard::number_row_layout().to_json().as_bytes(),
    )?;

    let personal = build_personal(root, &transcoder)?;
    let report = if verify {
        let built = first.built();
        let benches: Vec<(&str, &str)> = benches
            .iter()
            .map(|(n, b)| (n.as_str(), b.as_str()))
            .collect();
        let readers = trains
            .iter()
            .map(|(p, _)| open(p))
            .collect::<Result<Vec<_>, _>>()?;
        corpus_checks.extend(
            verify::leaks(&benches, readers).map_err(Error::io(root.join("build/corpus")))?,
        );
        let tables: Vec<(&str, u64)> = chars.iter().map(|(t, w)| (t.as_str(), *w)).collect();
        let frequency = lexicon::char_frequency(&tables)?;
        corpus_checks.push(verify::kept_characters(
            &frequency,
            &corpora::CANTONESE_KEPT,
        ));
        corpus_checks.push(verify::common_forms(&frequency, &forms));
        let decoded = |e: String| Error::invalid("資料包", e);
        let lexicon = built::decode::<LexiconPack>(&built).map_err(decoded)?;
        let model = built::decode::<LanguageModelPack>(&built)
            .map_err(decoded)?
            .model;
        corpus_checks.push(verify::lexicon_forms(&lexicon.lexicon, &model, &forms));

        // 第二次從來源重建速成碼表，其餘資料包也由它重建，整條鏈都比到。
        let second = build_packs(&build_quick()?, &second_chars, &second_words)?;
        let mut report = verify::run(&quick.rows, &built, &second.built());
        // Unihan 交叉比對的結果只寫報表，不影響通過與否。
        let check = unihan::compare(&quick.rows, &unihan::cangjie_codes(&quick.dictionary_like)?);
        let path = root.join(UNIHAN_REPORT);
        let reports = path.parent().expect("報表路徑有上層目錄");
        std::fs::create_dir_all(reports).map_err(Error::io(reports))?;
        write(path, check.to_tsv().as_bytes())?;
        report.unihan = Some(UnihanSummary {
            compared: check.compared,
            differences: check.differences.len(),
            matching_cangjie5: check.matching_cangjie5(),
            report: UNIHAN_REPORT.into(),
        });
        report.lexicon = Some(first.lexicon);
        report.language_model = Some(first.language_model);
        report.english = Some(first.english);
        report.emoji = Some(first.emoji);
        report.corpora = corpora.clone();
        report.checks.extend(corpus_checks);
        Some(report)
    } else {
        None
    };
    Ok(Outcome {
        packs,
        lexicon: first.lexicon,
        language_model: first.language_model,
        english: first.english,
        emoji: first.emoji,
        layout_path,
        corpora,
        personal,
        report,
    })
}

/// 方案 `[packs]` 指名的資料包 id；`key` 是方案檔的鍵，`what` 是錯誤訊息裡的種類名。
fn named(id: &Option<String>, key: &str, what: &str) -> Result<String, Error> {
    id.clone().ok_or_else(|| {
        Error::invalid(
            QUICK_SCHEME,
            format!("要在 [packs] 寫 {key}：{what}資料包的 id"),
        )
    })
}

/// 把資料包寫到 `build/packs/<id>/`，旁邊放 `LICENSE` 與 `NOTICE`；`packed` 是它讀好的授權。
fn write_pack(
    root: &Path,
    licensed: &LicensedPack,
    packed: &[packing::Packed],
) -> Result<WrittenPack, Error> {
    let BuiltPack {
        name, id, bytes, ..
    } = &licensed.pack;
    let dir = root.join(PACKS).join(id);
    packing::write(&dir, id, bytes, packed, &licensed.about)?;
    Ok(WrittenPack {
        name,
        id: id.clone(),
        path: dir.join(format!("{id}.pack")),
        sha256: licensed.pack.sha256(),
    })
}

