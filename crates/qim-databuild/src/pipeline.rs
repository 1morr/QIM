/// 詞庫資料包 NOTICE 最後一段：怎麼用來源。
fn lexicon_about(id: &str, scheme: &str) -> String {
    let list = |pairs: &[(char, char)], sep: &str| {
        pairs
            .iter()
            .map(|(a, b)| format!("{a}{sep}{b}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!(
        "{id} is the lexicon of the QIM input scheme \"{scheme}\". QIM changed the rime-essay\n\
         data as follows: single characters, words with a frequency below {min}, and words\n\
         containing characters outside the continuous set of the scheme were dropped; a word\n\
         listed more than once keeps its highest frequency. Every word was converted with\n\
         OpenCC t2hk, keeping {kept} as written, and then written in the common forms the\n\
         corpora use (for example 羣 as 群). Words that became the same word were merged:\n\
         equal frequencies (the same count listed under two forms, such as 巔峯 and 巔峰)\n\
         count once, different frequencies are added. Words that write the 著 of 著名 as 着\n\
         (any of {reversed}; this rime-essay version has only 顯着) were written with 著 and\n\
         merged the same way, so 顯着 went into 顯著. The words of\n\
         the QIM Cantonese colloquial word list, which only lists words the steps above left\n\
         out, were added with their listed frequencies. For the {both} character pairs whose\n\
         two forms are both kept ({pairs}), each such word is also listed in the other form\n\
         with the same frequency; for {one_way} (one way only, not the other way round) a\n\
         word with the first form is also listed with the second, merged the same way if that\n\
         word is already in the data, except {distinct}, whose second form is a different\n\
         word. Each word is indexed by the Quick codes of its characters joined, at most {max}\n\
         combinations per word.\n\
         \n\
         Character frequencies are the counts of each character in the training split of\n\
         each corpus, multiplied by the weight of that corpus ({weights}) and\n\
         added together; the two forms of a kept pair share their summed frequency.\n\
         {CORPUS_PREPROCESSING}",
        min = lexicon::MIN_FREQUENCY,
        max = lexicon::MAX_COMBINATIONS,
        weights = corpus_weights(),
        kept = ONE_WAY_FORMS.map(|(from, _)| from.to_string()).join(", "),
        reversed = REVERSED_ONE_WAY.join(", "),
        both = TWO_WAY_FORMS.len(),
        pairs = list(&TWO_WAY_FORMS, "/"),
        one_way = list(&ONE_WAY_FORMS, " -> "),
        distinct = ONE_WAY_DISTINCT.join(", "),
    )
}

/// 語言模型資料包 NOTICE 最後一段：怎麼用來源。授權是否要求模型同授權散布是 brief §11 的
/// 待決項，這裡不下結論。
fn language_model_about(id: &str) -> String {
    format!(
        "{id} is a character bigram language model trained by QIM with interpolated\n\
         Kneser-Ney smoothing. It was trained on the training split of each corpus listed\n\
         above, counting adjacent characters within each clause and multiplying the counts\n\
         of each corpus by its weight ({weights}), and pruned to the pairs whose weighted\n\
         count is at least {min}. {CORPUS_PREPROCESSING}",
        min = bigram::MIN_COUNT,
        weights = corpus_weights(),
    )
}

/// 各語料的權重（plan §4.3），寫進 NOTICE：`yue-wiki 1, zh-wiki 1, …`。
fn corpus_weights() -> String {
    CORPORA
        .iter()
        .map(|c| format!("{} {}", c.name, c.weight))
        .collect::<Vec<_>>()
        .join(", ")
}

/// 有 [`personal::USERDB`] 就轉出 [`personal::ITEMS`]；沒有就刪掉上次轉出的，基準才不會跑舊題目。
fn build_personal(root: &Path, transcoder: &Transcoder) -> Result<Option<personal::Counts>, Error> {
    let items = root.join(personal::ITEMS);
    let userdb = root.join(personal::USERDB);
    let text = match std::fs::read_to_string(&userdb) {
        Ok(text) => text,
        Err(e) if e.kind() == io::ErrorKind::NotFound => match std::fs::remove_file(&items) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => {
                return Err(Error::io(&items)(e));
            }
            _ => return Ok(None),
        },
        Err(e) => return Err(Error::io(&userdb)(e)),
    };
    let (tsv, counts) = personal::from_userdb(&text, transcoder)
        .map_err(|e| Error::invalid(personal::USERDB, e))?;
    let header = format!(
        "{}{}\n",
        personal::SOURCE_HEADER,
        sha256_hex(text.as_bytes())
    );
    std::fs::write(&items, header + &tsv).map_err(Error::io(&items))?;
    Ok(Some(counts))
}

/// 一份語料建一次；train、dev 寫進兩個 writer，同時算 sha256。寫入失敗時報 `dir`。
fn build_corpus<W: Write>(
    corpus: &Corpus,
    paths: &[PathBuf],
    forms: &CommonForms,
    transcoder: &Transcoder,
    train: Hashed<W>,
    dev: Hashed<W>,
    dir: &Path,
) -> Result<Built, Error> {
    let mut builder = Builder::new(transcoder, train, dev);
    corpus.texts(paths, forms, |text| {
        builder.add(text).map_err(Error::io(dir))
    })?;
    let Finished {
        counts,
        bench,
        dev_items,
        chars,
        train,
        dev,
    } = builder.finish().map_err(Error::io(dir))?;
    Ok(Built {
        counts,
        bench,
        dev_items,
        chars,
        train: train.sha256(),
        dev: dev.sha256(),
    })
}

fn open(path: &Path) -> Result<BufReader<File>, Error> {
    File::open(path)
        .map(BufReader::new)
        .map_err(Error::io(path))
}

/// 建一次語料的結果，train、dev 只留 sha256。
struct Built {
    counts: crate::corpus::Counts,
    bench: String,
    /// dev 的調參題；由 dev 切分決定，`dev` 的 sha256 相同它就相同，不另比。
    dev_items: String,
    chars: String,
    train: String,
    dev: String,
}

impl Built {
    /// 比較兩次建置用。
    fn digests(&self) -> CorpusDigests {
        CorpusDigests {
            bench: sha256_hex(self.bench.as_bytes()),
            train: self.train.clone(),
            dev: self.dev.clone(),
            chars: sha256_hex(self.chars.as_bytes()),
        }
    }
}
